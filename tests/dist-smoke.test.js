import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";
import { JSDOM, VirtualConsole } from "jsdom";

const builtDistUrl = new URL(
  "../.local/appamada_bmsir_submit.public-check.user.js",
  import.meta.url,
);
const publicDistUrl = new URL("../dist/appamada_bmsir_submit.user.js", import.meta.url);
const fixtureUrl = new URL("./fixtures/", import.meta.url);
const pageUrl =
  "https://bms-ir.org/new/song?songmd5=b89279d026c9d40d0f5eedde2e25b920&view=new";
const checkApiUrl = "https://script.google.com/macros/s/BUILD_CHECK_PLACEHOLDER/exec";
const rawUrl =
  "https://raw.githubusercontent.com/monsta-bms/appamada-tools/main/dist/appamada_bmsir_submit.user.js";
const apiUrlPattern = /apiUrl:\s*"(https:\/\/[^"\s]+)"/g;

function normalizeEol(value) {
  return value.replace(/\r\n?/g, "\n");
}

function configuredApiUrl(source) {
  const matches = [...source.matchAll(apiUrlPattern)];
  assert.equal(matches.length, 1, "bundle must configure exactly one API URL");
  return matches[0][1];
}

function assertReleaseMetadata(source, apiUrl) {
  assert.equal(source.startsWith("// ==UserScript=="), true);
  assert.match(source, /^\/\/ @name\s+不放逸 BMSIR申請$/m);
  assert.equal(source.match(/^\/\/ @version\s+(.+)$/m)?.[1], "0.4.8");
  assert.doesNotMatch(source, /採用されると管理者の○反映時にkkj/);
  assert.match(source, /^\/\/ @run-at\s+document-idle$/m);
  assert.match(source, /^\/\/ @noframes$/m);
  assert.match(source, /^\/\/ @updateURL\s+https:\/\/raw\.githubusercontent\.com\/monsta-bms\/appamada-tools\/main\/dist\/appamada_bmsir_submit\.user\.js$/m);
  assert.match(source, /^\/\/ @downloadURL\s+https:\/\/raw\.githubusercontent\.com\/monsta-bms\/appamada-tools\/main\/dist\/appamada_bmsir_submit\.user\.js$/m);
  assert.equal(source.includes(rawUrl), true);

  assert.deepEqual(source.match(/^\/\/ @match\s+.+$/gm), [
    "// @match        https://bms-ir.org/new/song*",
    "// @match        https://www.bms-ir.org/new/song*",
  ]);
  assert.deepEqual(source.match(/^\/\/ @grant\s+.+$/gm), [
    "// @grant        GM_xmlhttpRequest",
    "// @grant        GM_addStyle",
    "// @grant        GM.getValue",
    "// @grant        GM.setValue",
    "// @grant        GM.deleteValue",
    "// @grant        GM.listValues",
    "// @grant        GM_getValue",
    "// @grant        GM_setValue",
    "// @grant        GM_deleteValue",
    "// @grant        GM_listValues",
  ]);
  assert.deepEqual(source.match(/^\/\/ @connect\s+.+$/gm), [
    "// @connect      script.google.com",
    "// @connect      script.googleusercontent.com",
    ...(new URL(apiUrl).hostname === "script.google.com" ? [] : [
      `// @connect      ${new URL(apiUrl).hostname}`,
    ]),
  ]);
}

function assertPublishedMatchesCandidate(builtSource, publicSource) {
  const builtApiUrl = configuredApiUrl(builtSource);
  const publicApiUrl = configuredApiUrl(publicSource);
  assert.equal(builtApiUrl, checkApiUrl);
  const endpoint = new URL(publicApiUrl);
  assert.equal(endpoint.protocol, "https:");
  assert.match(endpoint.hostname, /^[a-z0-9-]+\.[a-z0-9-]+\.workers\.dev$/);
  assert.equal(endpoint.pathname, "/api");
  assert.equal(endpoint.username, "");
  assert.equal(endpoint.password, "");
  assert.equal(endpoint.port, "");
  assert.equal(endpoint.search, "");
  assert.equal(endpoint.hash, "");
  assert.doesNotMatch(publicApiUrl, /test|placeholder/i);
  assertReleaseMetadata(builtSource, builtApiUrl);
  assertReleaseMetadata(publicSource, publicApiUrl);

  // The public release may differ only in its configured endpoint and the
  // corresponding exact-host permission generated by buildSubmission.
  const normalizedPublic = publicSource
    .replace(`// @connect      ${endpoint.hostname}\n`, "")
    .replace(`apiUrl: "${publicApiUrl}"`, `apiUrl: "${builtApiUrl}"`);
  assert.equal(normalizedPublic, builtSource,
    "published bundle must match the current candidate except for endpoint configuration");
}

test("published release and local source candidate keep release metadata, exact permissions, and matching code", async () => {
  const [builtSourceRaw, publicSourceRaw] = await Promise.all([
    readFile(builtDistUrl, "utf8"),
    readFile(publicDistUrl, "utf8"),
  ]);
  const builtSource = normalizeEol(builtSourceRaw);
  const publicSource = normalizeEol(publicSourceRaw);
  assertPublishedMatchesCandidate(builtSource, publicSource);
  assert.doesNotThrow(() => new Function(builtSource));
  assert.doesNotMatch(builtSource, /sourceMappingURL|GATEWAY_SHARED_SECRET/);

  assert.doesNotMatch(publicSource, /sourceMappingURL/);
  assert.doesNotMatch(publicSource, /node:test|tests\/fixtures|dist-smoke/);
  assert.doesNotMatch(publicSource, /0\.2\.0-test|0\.3\.0-rc\.1|Production Candidate/);
  assert.doesNotThrow(() => new Function(publicSource));
});

test("release parity guard rejects broadened permissions and code drift", async () => {
  const [builtSourceRaw, publicSourceRaw] = await Promise.all([
    readFile(builtDistUrl, "utf8"), readFile(publicDistUrl, "utf8"),
  ]);
  const builtSource = normalizeEol(builtSourceRaw);
  const publicSource = normalizeEol(publicSourceRaw);
  assert.throws(() => assertPublishedMatchesCandidate(builtSource,
    publicSource.replace("// @run-at", "// @connect      *\n// @run-at")));
  assert.throws(() => assertPublishedMatchesCandidate(builtSource,
    `${publicSource}\n// unexpected source difference\n`));
});

test("local candidate initializes old and current logged-in DOM with one lookup prefetch", async () => {
  const source = await readFile(builtDistUrl, "utf8");
  for (const fixtureName of ["logged-in-song.html", "logged-in-song-current.html"]) {
    const html = await readFile(new URL(fixtureName, fixtureUrl), "utf8");
    const virtualConsole = new VirtualConsole();
    const consoleErrors = [];
    virtualConsole.on("jsdomError", (error) => consoleErrors.push(error));
    const dom = new JSDOM(html, { url: pageUrl, runScripts: "outside-only", virtualConsole });
    let requests = 0;
    let styles = 0;
    dom.window.GM_xmlhttpRequest = (details) => {
      requests += 1;
      assert.equal(details.method, "GET");
      assert.match(details.url, /[?&]action=lookup(?:&|$)/);
    };
    dom.window.GM_addStyle = () => { styles += 1; };

    assert.doesNotThrow(() => dom.window.eval(source));
    assert.equal(requests, 1);
    assert.equal(styles, 1);
    assert.deepEqual(consoleErrors, []);
    dom.window.close();
  }
});

test("local candidate leaves a logged-out page untouched", async () => {
  const [source, html] = await Promise.all([
    readFile(builtDistUrl, "utf8"),
    readFile(new URL("logged-out-song.html", fixtureUrl), "utf8"),
  ]);
  const dom = new JSDOM(html, { url: pageUrl, runScripts: "outside-only" });
  let externalCalls = 0;
  dom.window.GM_xmlhttpRequest = () => { externalCalls += 1; };
  dom.window.GM_addStyle = () => { externalCalls += 1; };
  const before = dom.serialize();

  assert.doesNotThrow(() => dom.window.eval(source));
  assert.equal(dom.serialize(), before);
  assert.equal(externalCalls, 0);
  dom.window.close();
});

test("fatal parse failure emits a structured warning with no page text", async () => {
  const [source, html] = await Promise.all([
    readFile(builtDistUrl, "utf8"),
    readFile(new URL("logged-in-song-current.html", fixtureUrl), "utf8"),
  ]);
  const virtualConsole = new VirtualConsole();
  const warnings = [];
  virtualConsole.on("warn", (...args) => warnings.push(args));
  const dom = new JSDOM(html, { url: pageUrl, runScripts: "outside-only", virtualConsole });
  const title = dom.window.document.querySelector("#main-content > h1");
  title.after(title.cloneNode(true));
  dom.window.GM_xmlhttpRequest = () => {};
  dom.window.GM_addStyle = () => {};

  assert.doesNotThrow(() => dom.window.eval(source));
  assert.equal(warnings.length, 1);
  const serialized = JSON.stringify(warnings[0]);
  assert.match(serialized, /PARSE_FAILED/);
  assert.match(serialized, /SONG_DOM_INVALID/);
  assert.match(serialized, /currentTitleMatches/);
  assert.doesNotMatch(serialized, /FixtureUser|図書室|b89279/i);
  dom.window.close();
});

test("local candidate saves offline in GM storage and resends after page reopen (modern and legacy APIs)", async (t) => {
  const opened = [];
  t.after(() => { for (const dom of opened) dom.window.close(); });
  const [source, html] = await Promise.all([
    readFile(builtDistUrl, "utf8"), readFile(new URL("logged-in-song-current.html", fixtureUrl), "utf8"),
  ]);
  async function until(check) {
    for (let n = 0; n < 100; n++) {
      if (check()) return;
      await new Promise((resolve) => setTimeout(resolve, 2));
    }
    assert.fail("bundle did not settle");
  }
  for (const storageApi of ["modern", "legacy"]) {
    const values = new Map();
    const posted = [];
    let time = Date.now();
    function page(offline) {
      const dom = new JSDOM(html, { url: pageUrl, runScripts: "outside-only" });
      opened.push(dom);
      dom.window.Date.now = () => time;
      const get = (key) => values.has(key) ? structuredClone(values.get(key)) : undefined;
      const set = (key, value) => values.set(key, structuredClone(value));
      const remove = (key) => values.delete(key);
      const keys = () => [...values.keys()];
      if (storageApi === "modern") dom.window.GM = {
        getValue: async (key) => get(key), setValue: async (key, value) => { set(key, value); },
        deleteValue: async (key) => { remove(key); }, listValues: async () => keys(),
      };
      else Object.assign(dom.window, { GM_getValue: get, GM_setValue: set,
        GM_deleteValue: remove, GM_listValues: keys });
      dom.window.GM_addStyle = () => {};
      dom.window.GM_xmlhttpRequest = (details) => {
        queueMicrotask(() => {
          if (offline) { details.onerror(); return; }
          let result = { ok: true, exists: false };
          if (details.method === "POST") {
            const body = JSON.parse(details.data);
            posted.push(body);
            result = { ok: true, request_id: body.request_id, deduplicated: false };
          }
          details.onload({ status: 200, responseText: JSON.stringify(result) });
        });
      };
      dom.window.eval(source);
      return dom;
    }
    const first = page(true);
    await new Promise((resolve) => setTimeout(resolve, 5));
    first.window.document.querySelector("#main-content > h1").dispatchEvent(
      new first.window.MouseEvent("contextmenu", { bubbles: true, cancelable: true }),
    );
    first.window.document.querySelector('[data-action="change"]').click();
    await until(() => first.window.document.querySelector('[data-level="13-"]'));
    assert.match(first.window.document.querySelector(".appamada-modal").textContent,
      /通信不具合中。現時点の難易度表データ取得できません/);
    first.window.document.querySelector('[data-level="13-"]').click();
    first.window.document.querySelector(".appamada-submit").click();
    await until(() => first.window.document.querySelector(".appamada-submit").textContent.includes("保存済み"));
    assert.equal(posted.length, 0);
    const saved = [...values.entries()].find(([key]) => key.includes("entry."))[1];
    assert.equal(saved.payload.client_version, "0.4.8");
    first.window.dispatchEvent(new first.window.Event("pagehide"));
    first.window.close();
    time += 30_001;
    const second = page(false);
    await until(() => [...values.keys()].some((key) => key.includes("receipt.")));
    assert.equal(posted.length, 1);
    assert.deepEqual(posted[0], saved.payload);
    second.window.dispatchEvent(new second.window.Event("pagehide"));
    second.window.close();
  }
});
